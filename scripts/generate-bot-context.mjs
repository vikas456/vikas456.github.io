/**
 * Builds the chatbot's knowledge base into worker/src/context.generated.ts.
 *
 * The site's own facts are read straight out of src/data/*.ts, so the bot can
 * never contradict the page — editing the timeline updates the bot on the next
 * build. Only the résumé and the LinkedIn snapshot, which live nowhere else,
 * come from content/bio-source.md.
 *
 * Run via `npm run bot:context`, and automatically as part of `npm run build`.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...s) => resolve(root, ...s);

const strip = (html) => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

/** Pull an exported array/object literal out of a TS module without importing it. */
async function readSource(file) {
  return readFile(p('src/data', file), 'utf8');
}

const content = await readSource('content.ts');
const site = await readSource('site.ts');
const bio = await readFile(p('content/bio-source.md'), 'utf8');

/* ---- timeline ---- */
const timeline = [...content.matchAll(
  /when: '([^']+)',\s*\n\s*title: '([^']+)',\s*\n(?:\s*badge: '([^']+)',\s*\n)?\s*org: '([^']+)',\s*\n\s*bullets: \[([\s\S]*?)\n\s*\],/g,
)].map(([, when, title, badge, org, bullets]) => {
  const lines = [...bullets.matchAll(/'((?:[^'\\]|\\.)*)'/g)]
    .map((m) => strip(m[1].replace(/\\'/g, "'")))
    .filter(Boolean);
  return `${title}${badge ? ` (${badge})` : ''} — ${org}, ${when}\n${lines.map((l) => `  - ${l}`).join('\n')}`;
}).join('\n\n');

/* ---- selected work ---- */
const work = [...content.matchAll(
  /title: '((?:[^'\\]|\\.)*)',\s*\n\s*chip: '([^']*)',[\s\S]*?body:\s*"((?:[^"\\]|\\.)*)"[\s\S]*?(?:impact: '([^']*)',)?\s*\n\s*stack: \[([^\]]*)\]/g,
)].map(([, title, chip, body, impact, stack]) => {
  const tech = [...stack.matchAll(/'([^']+)'/g)].map((m) => m[1]).join(', ');
  return `${title.replace(/\\'/g, "'")} [${chip}]${impact ? ` — ${impact}` : ''}\n  ${body.replace(/\\"/g, '"')}\n  Tech: ${tech}`;
}).join('\n\n');

/* ---- reach diagram: products and the projects under each ---- */
const products = [...content.matchAll(
  /label: '((?:[^'\\]|\\u[0-9a-fA-F]{4}|[^'])*)',\s*\n\s*group: '[^']*',[\s\S]*?did:\s*'((?:[^'\\]|\\.)*)',\s*\n\s*metric: '([^']*)',\s*\n\s*children: \[([\s\S]*?)\n\s*\],/g,
)].map(([, label, did, metric, kids]) => {
  const items = [...kids.matchAll(/label: '((?:[^'\\]|\\.)*)',\s*\n\s*detail:\s*\n?\s*'((?:[^'\\]|\\.)*)'/g)]
    .map((m) => `  - ${m[1]}: ${m[2]}`.replace(/\\u2019/g, '’').replace(/\\u2014/g, '—'));
  return `${label.replace(/\\u00b7/g, '·')} — ${did} (${metric})\n${items.join('\n')}`;
}).join('\n\n').replace(/\\u2019/g, '’').replace(/\\u2014/g, '—');

/* ---- identity + links ---- */
const field = (name, src = site) => (src.match(new RegExp(`${name}:\\s*\\n?\\s*'([^']*)'`)) || [])[1] ?? '';
const identity = [
  `Name: ${field('name')}`,
  `Role: ${field('role')}`,
  `Location: ${field('location')}`,
  `Work authorisation: ${field('citizenship')}`,
  `Availability: ${field('status')}`,
  `Email: ${field('email')}`,
  `LinkedIn: ${field('linkedin')}`,
  `GitHub: ${field('github')}`,
  `Résumé: ${field('resume')}`,
].join('\n');

const corpus = `# Vikas Peraka — reference

## Identity and contact
${identity}

## Career timeline
${timeline}

## Products and the projects behind each
${products}

## Selected work
${work}

${bio.replace(/<!--[\s\S]*?-->\n*/, '')}
`.trim();

const out = `// GENERATED by scripts/generate-bot-context.mjs — do not edit by hand.
// Regenerate with \`npm run bot:context\`.
export const CONTEXT = ${JSON.stringify(corpus)};
`;

await writeFile(p('worker/src/context.generated.ts'), out);

const approxTokens = Math.round(corpus.length / 4);
console.log(`✓ bot context: ${corpus.length} chars (~${approxTokens} tokens)`);
if (approxTokens > 12000) console.warn('  ! context is getting large — check the generator is not duplicating sections');
